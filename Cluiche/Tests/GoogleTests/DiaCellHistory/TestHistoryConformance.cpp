// ---- live follow (AC 12) ---------------------------------------------------------------------------------------------------

namespace
{
	// Pages one aggregates range [from, to) with the current budget and appends the rows to the series.
	void CatchUpAggregates(HistoryQueries& q, uint32_t from, uint32_t to, Series& out, uint32_t& pages)
	{
		Json::Value args = Obj();
		args["from"] = from; args["to"] = to;
		for (int guard = 0; guard < 100000; ++guard)
		{
			const Json::Value rep = q.Aggregates(args);
			ASSERT_FALSE(rep.isMember("error")) << rep["error"].asString();
			++pages;
			out.Add(rep);
			if (!rep.isMember("next")) { return; }
			args["from"] = rep["next"]["from"];
		}
		ADD_FAILURE() << "runaway paging";
	}

	void CatchUpEvents(HistoryQueries& q, uint32_t from, uint32_t to, std::vector<Json::Value>& out, uint32_t& pages)
	{
		Json::Value args = Obj();
		args["from"] = from; args["to"] = to;
		for (int guard = 0; guard < 100000; ++guard)
		{
			const Json::Value rep = q.Events(args);
			ASSERT_FALSE(rep.isMember("error")) << rep["error"].asString();
			++pages;
			for (const Json::Value& e : rep["events"]) { out.push_back(e); }
			if (!rep.isMember("next")) { return; }
			args["from"] = rep["next"]["from"];
			args["skip"] = rep["next"]["skip"];
		}
		ADD_FAILURE() << "runaway paging";
	}

	std::vector<Json::Value> AllEvents(const std::vector<Json::Value>& msgs)
	{
		std::vector<Json::Value> out;
		for (const Json::Value& m : msgs) { for (const Json::Value& e : m["events"]) { out.push_back(e); } }
		return out;
	}
}

TEST(HistoryConformanceFollow, JoinMidRunWithPagedCatchUpThenTopicsReproduceTheFile)
{
	Scn s;
	s.Setup();
	ASSERT_FALSE(HasFatalFailure());
	TempFolder tmp;
	s.Step(17);								// history before the client exists
	s.TickAt(0.0);							// nobody subscribed: topics idle, cursors at the head
	HistoryQueries q(*s.r.rec);
	q.SetMaxReplyBytes(1800);				// forces many pages, events resume mid-sample
	q.SetMaxEvents(3);
	s.topics->SetMaxEventsPerMessage(2);

	// 1. subscribe (the topics start at the head); 2. follow for a while; 3. catch up the history before the first topic row by query.
	s.pub.subs = 1;
	s.TickAt(1.0);
	double t = 1.0;
	for (int round = 0; round < 6; ++round) { s.Step(3); s.TickAt(t += 1.0); }
	s.Step(1); s.TickAt(t += 1.0);
	const std::vector<Json::Value> aggMsgs = s.pub.Of(kAggTopic);
	ASSERT_GE(aggMsgs.size(), 1u);
	const uint32_t join = aggMsgs[0]["fromSample"].asUInt();
	ASSERT_EQ(join, 17u);

	const Json::Value meta = q.Meta(Obj());
	ASSERT_FALSE(meta.isMember("error")) << meta["error"].asString();
	char hex[24];
	snprintf(hex, sizeof(hex), "%016llx", (unsigned long long)s.r.rec->StructureHash());
	EXPECT_EQ(meta["structure"].asString(), hex);
	EXPECT_EQ(aggMsgs[0]["structure"].asString(), hex);

	Series client;
	std::vector<Json::Value> clientEvents;
	uint32_t aggPages = 0, evPages = 0;
	CatchUpAggregates(q, 0, join, client, aggPages);
	CatchUpEvents(q, 0, join, clientEvents, evPages);
	ASSERT_FALSE(HasFatalFailure());
	EXPECT_GT(aggPages, 3u);
	EXPECT_GT(evPages, 2u);
	ASSERT_EQ(client.samples, join);
	for (const Json::Value& m : aggMsgs)
	{
		ASSERT_EQ(m["fromSample"].asUInt(), client.samples);		// contiguous with the catch-up and with each other
		client.Add(m);
	}
	for (const Json::Value& e : AllEvents(s.pub.Of(kEvTopic))) { clientEvents.push_back(e); }

	ExportResult res;
	const std::string path = tmp.File("run.cell_history.json");
	ASSERT_TRUE(HistoryExporter::WriteFile(*s.r.rec, s.Options(false), path.c_str(), res)) << res.error;
	DecodedExport dec;
	ASSERT_TRUE(dec.Load(path.c_str()));
	client.ExpectEqualsFile(dec, 0);
	ASSERT_EQ(client.samples, dec.SampleCount());
	// Events: no duplicates, no gaps, same order, same content.
	ASSERT_EQ(clientEvents.size(), size_t(dec.root["events"].size()));
	for (size_t i = 0; i < clientEvents.size(); ++i) { EXPECT_TRUE(JsonEq(clientEvents[i], dec.root["events"][Json::ArrayIndex(i)])) << i; }
	EXPECT_GT(clientEvents.size(), 10u);
}

TEST(HistoryConformanceFollow, StructureChangeInTheTopicForcesAMetaRefetchThatMatches)
{
	Scn s;
	s.Setup();
	ASSERT_FALSE(HasFatalFailure());
	TempFolder tmp;
	HistoryQueries q(*s.r.rec);

	// The client joins before the first sample: the layout is not resolved yet, so meta carries the pre-layout structure.
	s.pub.subs = 1;
	s.TickAt(0.0);
	const Json::Value before = q.Meta(Obj());
	ASSERT_FALSE(before.isMember("error")) << before["error"].asString();
	EXPECT_EQ(before["header"]["sampleCount"].asUInt(), 0u);
	const std::string oldStructure = before["structure"].asString();

	s.Step(3); s.TickAt(1.0);
	const std::vector<Json::Value> first = s.pub.Of(kAggTopic);
	ASSERT_EQ(first.size(), 1u);
	EXPECT_TRUE(first[0]["structureChanged"].asBool());
	EXPECT_NE(first[0]["structure"].asString(), oldStructure);
	EXPECT_EQ(first[0]["fromSample"].asUInt(), 0u);

	// The client re-fetches meta: it now shows the new structure, the layers and the groups the rows refer to.
	const Json::Value after = q.Meta(Obj());
	ASSERT_FALSE(after.isMember("error")) << after["error"].asString();
	EXPECT_EQ(after["structure"].asString(), first[0]["structure"].asString());
	EXPECT_GT(after["layers"].size(), before["layers"].size());
	EXPECT_GE(after["groups"].size(), 4u);

	Series client;
	double t = 1.0;
	client.Add(first[0]);
	for (int round = 0; round < 4; ++round) { s.Step(2); s.TickAt(t += 1.0); }
	const std::vector<Json::Value> all = s.pub.Of(kAggTopic);
	for (size_t i = 1; i < all.size(); ++i)
	{
		EXPECT_FALSE(all[i].isMember("structureChanged")) << i;
		EXPECT_EQ(all[i]["structure"].asString(), after["structure"].asString());
		ASSERT_EQ(all[i]["fromSample"].asUInt(), client.samples);
		client.Add(all[i]);
	}
	EXPECT_EQ(q.Meta(Obj())["structure"].asString(), after["structure"].asString());		// samples never change it

	ExportResult res;
	const std::string path = tmp.File("run.cell_history.json");
	ASSERT_TRUE(HistoryExporter::WriteFile(*s.r.rec, s.Options(false), path.c_str(), res)) << res.error;
	DecodedExport dec;
	ASSERT_TRUE(dec.Load(path.c_str()));
	client.ExpectEqualsFile(dec, 0);
	EXPECT_EQ(client.samples, dec.SampleCount());
}

