	for (Json::ArrayIndex i = 0; i < schema["entries"].size(); ++i) { EXPECT_TRUE(JsonEq(schema["entries"][i], file.root["schema"]["entries"][i])) << i; }

	// aggregates page: decoded rows equal the file's first `count` samples.
	ASSERT_EQ(agg["from"].asUInt(), 0u);
	ASSERT_GE(agg["count"].asUInt(), 1u);
	ASSERT_LT(agg["count"].asUInt(), kRunSamples);
