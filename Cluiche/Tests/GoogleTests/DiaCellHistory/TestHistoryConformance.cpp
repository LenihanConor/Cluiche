TEST(HistoryConformance, CommittedFixturesEqualTheRegeneratedBytes)
{
	ConformanceRun run;
	run.Run();
	ASSERT_FALSE(HasFatalFailure());
	const std::filesystem::path folder = FixtureFolder();
	ASSERT_FALSE(folder.empty()) << "Dia/DiaCellHistory/Testing/Conformance not found above " << __FILE__;
	if (RegenRequested())
	{
		for (const auto& kv : run.files)
		{
			std::ofstream f(folder / kv.first, std::ios::binary | std::ios::trunc);
			ASSERT_TRUE(f.good()) << "cannot write " << kv.first;
			f << kv.second;
		}
		printf("[ conformance ] regenerated %zu fixture files in %s\n", run.files.size(), folder.string().c_str());
		return;
	}
	for (const auto& kv : run.files)
	{
		std::string committed;
		ASSERT_TRUE(VsTest::ReadFileBytes(folder / kv.first, committed)) << kv.first << " is missing; regenerate with DIA_UPDATE_GOLDEN=1";
		EXPECT_EQ(StripCr(committed), StripCr(kv.second)) << kv.first << " differs from the code's output; if the format change is deliberate, regenerate with DIA_UPDATE_GOLDEN=1 and review the diff";
	}
	// A committed .json that the generator no longer produces is stale.
	for (const auto& entry : std::filesystem::directory_iterator(folder))
	{
		if (entry.path().extension() == ".json") { EXPECT_TRUE(run.files.count(entry.path().filename().string()) != 0) << "stale fixture " << entry.path().filename().string(); }
	}
}

