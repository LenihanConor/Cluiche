def _snapshot(root: Path) -> dict:
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in root.rglob("*") if p.is_file()}


def _run(*args):
    return CliRunner().invoke(stage_cmd.stage, list(args))


def _json(repo: Path, rel: str):
    return json.loads((repo / rel).read_text(encoding="utf-8"))


def test_help_documents_app_option():
    result = _run("--help")
    assert "--app" in result.output


def test_creates_and_edits_exactly_the_expected_files(repo):
    before = _snapshot(repo)
    result = _run("Combat", "--app", "CoW")
    assert result.exit_code == 0, result.output
    after = _snapshot(repo)
    created = {k for k in after if k not in before}
    changed = {k for k in after if k in before and before[k] != after[k]}
    assert created == APP_FILES
    assert changed == APP_EDITED
    assert set(before) - set(after) == set()


def test_module_uses_app_namespace_and_app_include_path(repo):
    _run("Combat", "--app", "CoW")
    h = (repo / "Cluiche/CoW/Modules/CombatModule.h").read_text(encoding="utf-8")
    cpp = (repo / "Cluiche/CoW/Modules/CombatModule.cpp").read_text(encoding="utf-8")
    assert "namespace CoW {" in h and "class CombatModule" in h
    assert '#include "Modules/CombatModule.h"' in cpp
    assert "DIA_MODULE(CombatModule_);" in cpp
    assert "CluicheTest" not in h + cpp and "TestStage" not in h + cpp


def test_module_matches_app_generator_output(repo):
    """The stage module is the same template `dia scaffold app` uses for its initial stage."""
    _run("Combat", "--app", "CoW")
    front_h = (repo / "Cluiche/CoW/Modules/FrontEndModule.h").read_text(encoding="utf-8")
    combat_h = (repo / "Cluiche/CoW/Modules/CombatModule.h").read_text(encoding="utf-8")
    assert combat_h == front_h.replace("FrontEnd", "Combat")
    front_cpp = (repo / "Cluiche/CoW/Modules/FrontEndModule.cpp").read_text(encoding="utf-8")
    combat_cpp = (repo / "Cluiche/CoW/Modules/CombatModule.cpp").read_text(encoding="utf-8")
    assert combat_cpp == front_cpp.replace("FrontEnd", "Combat")


def test_stage_files_match_app_generator_output(repo):
    _run("Combat", "--app", "CoW")
    base = "Cluiche/Assets/CoW/Stages/"
    for suffix_new, suffix_old in (
        ("Combat/combat.diastage", "FrontEnd/front_end.diastage"),
        ("Combat/misc/ApplicationFlow/combat.diaapp", "FrontEnd/misc/ApplicationFlow/front_end.diaapp"),
    ):
        new = (repo / base / suffix_new).read_text(encoding="utf-8")
        old = (repo / base / suffix_old).read_text(encoding="utf-8")
        assert new == old.replace("FrontEnd", "Combat").replace("front_end", "combat")


