def test_catalogue_entries_use_snake_stage_id(repo):
    _run("Combat", "--app", "CoW")
    cat = _json(repo, "Cluiche/Assets/CoW/assets.catalogue.json")
    by_id = {a["id"]: a for a in cat["assets"]}
    st = by_id["stage.combat"]
    assert st["type"] == "stage" and st["scope"] == "global"
    assert st["source_path"] == "Stages/Combat/combat.diastage"
    assert st["references"] == [{"target": "manifest.combat", "type": "contains"}]
    mf = by_id["manifest.combat"]
    assert mf["scope"] == "stage" and mf["stage_name"] == "Combat"
    assert mf["source_path"] == "Stages/Combat/misc/ApplicationFlow/combat.diaapp"
    # Same shape as the generated FrontEnd entries
    assert set(st) == set(by_id["stage.front_end"]) and set(mf) == set(by_id["manifest.front_end"])


