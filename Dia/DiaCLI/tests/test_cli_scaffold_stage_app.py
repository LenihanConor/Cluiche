def test_dry_run_lists_nine_paths_and_writes_nothing(repo):
    before = _snapshot(repo)
    result = _run("Combat", "--app", "CoW", "--dry-run")
    assert result.exit_code == 0, result.output
    assert _snapshot(repo) == before
    lines = [l for l in result.output.splitlines() if "Create" in l or "Update" in l]
    assert len(lines) == 9
    for rel in APP_FILES | APP_EDITED:
        assert rel in result.output


