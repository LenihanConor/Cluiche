def test_vcxproj_and_filters_entries(repo):
    _run("Combat", "--app", "CoW")
    proj = (repo / "Cluiche/CoW/CoW.vcxproj").read_text(encoding="utf-8")
    assert proj.count('<ClCompile Include="Modules\\CombatModule.cpp" />') == 1
    assert proj.count('<ClInclude Include="Modules\\CombatModule.h" />') == 1
    flt = (repo / "Cluiche/CoW/CoW.vcxproj.filters").read_text(encoding="utf-8")
    assert '<ClCompile Include="Modules\\CombatModule.cpp">' in flt
    assert '<ClInclude Include="Modules\\CombatModule.h">' in flt
    assert flt.count("<Filter>Modules</Filter>") == 4  # FrontEnd cpp+h, Combat cpp+h


