"""Tests for `dia docs value-reference` and its precommit hook."""
from __future__ import annotations

import json

import pytest
from click.testing import CliRunner

from dia_cli.commands.docs import value_reference as vr
from dia_cli.commands.docs.group import docs_group
from dia_cli.commands.docs import precommit_cmd


def _entry(key, **kw):
    e = {"key": key, "kind": "parameter", "label": key.title(), "description": f"About {key}", "type": "float"}
    e.update(kw)
    return e


def _sidecar(fmt, entries):
    return {"format": "dia.value_schema", "version": 1, "for": fmt, "entries": entries}


def _export(**over):
    doc = {
        "format": "dia.value_schema_export", "version": 1,
        "header": {"app": "Demo", "config": "Debug", "git_commit": "abc1234def", "dirty": False,
                   "generated_at": "2026-10-22T10:00:00Z"},
        "entries": [
            {"key": "frame_ms", "kind": "metric", "origin": "code:metric", "label": "Frame", "description": "Frame time",
             "unit": "ms", "type": "float"},
            {"key": "render.draws", "kind": "metric", "origin": "code:metric", "description": "", "type": "int"},
            {"key": "spawn", "kind": "command", "origin": "code:command", "description": "Spawns",
             "ui": {"owner": "Sim", "category": "World", "example": "spawn 3"}},
            {"key": "spawn.count", "kind": "arg", "origin": "code:arg", "description": "How many", "type": "int",
             "min": 1, "max": 9, "default": 1},
            {"key": "quit", "kind": "command", "origin": "code:command", "description": "Quits",
             "ui": {"owner": "Sim", "no_args": True}},
            {"key": "Transform/x", "kind": "component_field", "origin": "code:component_field",
             "description": "X pos", "type": "float", "min": -5, "max": 5},
            {"key": "w/gravity", "kind": "parameter", "origin": "sidecar:a.schema.json", "label": "dup",
             "description": "must not show in code tables", "type": "float"},
        ],
        "undescribed": {"metrics": [{"name": "render.draws", "owner": "Render"}],
                        "commands": [{"name": "spawn", "owner": "Sim", "args": ["count"]}],
                        "component_fields": []},
    }
    doc.update(over)
    return doc


@pytest.fixture
def repo(tmp_path, monkeypatch):
    app = tmp_path / "Cluiche" / "Assets" / "Demo"
    app.mkdir(parents=True)
    (app / "b.schema.json").write_text(json.dumps(_sidecar("beta.format", [
        _entry("zeta", unit="m", min=0, max=10, default=3, affects=["beta.format/alpha"], description="a | b\nline2 `code`"),
        _entry("alpha", type="int"),
    ])), encoding="utf-8")
    (app / "a.schema.json").write_text(json.dumps(_sidecar("alpha.format", [
        _entry("gravity", unit="m/s2", default=9.8),
    ])), encoding="utf-8")
    (app / "notes.json").write_text("{not json", encoding="utf-8")
    monkeypatch.setattr(vr, "_repo_root", lambda: tmp_path)
    return tmp_path


def _write_export(repo, doc):
    out = repo / "Cluiche" / "out" / "Demo"
    out.mkdir(parents=True, exist_ok=True)
    (out / "valueschema.json").write_text(json.dumps(doc), encoding="utf-8")


def _gen(repo):
    return vr.generate("Demo", repo)


def test_format_tables_have_all_columns_sorted(repo):
    _, text = _gen(repo)
    assert "| Key | Label | Type | Unit | Range | Default | Description | Affects |" in text
    assert text.index("alpha.format") < text.index("beta.format")
    assert text.index("`alpha`") < text.index("`zeta`")
    assert "0 .. 10" in text and "`beta.format/alpha`" in text


def test_no_export_replaces_code_side_tables(repo):
    path, text = _gen(repo)
    assert path == repo / "docs" / "reference" / "demo" / "values.md"
    assert "Generated by `dia docs value-reference`, do not edit" in text
    assert "no export was found" in text and "dia schema export" in text
    assert "## Metrics" not in text and "## Commands" not in text and "## Component fields" not in text


def test_code_side_false_acts_like_no_export(repo):
    doc = _export()
    doc["header"]["code_side"] = False
    _write_export(repo, doc)
    _, text = _gen(repo)
    assert "dia schema export" in text
    assert "## Metrics" not in text


def test_export_tables(repo):
    _write_export(repo, _export())
    _, text = _gen(repo)
    assert "abc1234def" in text
    assert "## Metrics" in text and "`frame_ms`" in text
    assert "## Commands" in text and "`spawn`" in text and "`count`" in text
    assert "no arguments" in text
    assert "## Component fields" in text and "`Transform/x`" in text
    assert "must not show in code tables" not in text
    assert "dia schema export" not in text


def test_undescribed_marked(repo):
    _write_export(repo, _export())
    _, text = _gen(repo)
    assert "## Undescribed" in text
    assert "Metrics: 1" in text and "Commands: 1" in text and "Component fields: 0" in text


def test_deterministic(repo):
    _write_export(repo, _export())
    assert _gen(repo)[1] == _gen(repo)[1]
    assert "2026-10-22T10" not in _gen(repo)[1]


def test_cell_escaping(repo):
    _, text = _gen(repo)
    row = next(l for l in text.splitlines() if l.startswith("| `zeta`"))
    assert "a \| b<br>line2 `code`" in row


def test_cli_writes_then_check(repo):
    r = CliRunner()
    assert r.invoke(docs_group, ["value-reference", "--target", "Demo", "--check"]).exit_code == 1
    res = r.invoke(docs_group, ["value-reference", "--target", "Demo"])
    assert res.exit_code == 0, res.output
    page = repo / "docs" / "reference" / "demo" / "values.md"
    assert page.is_file()
    assert r.invoke(docs_group, ["value-reference", "--target", "Demo", "--check"]).exit_code == 0
    page.write_text("stale\n", encoding="utf-8")
    res = r.invoke(docs_group, ["value-reference", "--target", "Demo", "--check"])
    assert res.exit_code == 1
    assert "values.md" in res.output and "dia docs value-reference --target Demo" in res.output


def test_precommit_warns_only_when_out_of_date(repo):
    changed = [repo / "Cluiche" / "Assets" / "Demo" / "b.schema.json"]
    assert "reference out of date" in "\n".join(precommit_cmd._check_value_reference(repo, changed))
    path, text = _gen(repo)
    path.parent.mkdir(parents=True)
    path.write_text(text, encoding="utf-8")
    assert precommit_cmd._check_value_reference(repo, changed) == []
    path.write_text("stale", encoding="utf-8")
    assert precommit_cmd._check_value_reference(repo, [path]) != []
    other = repo / "Cluiche" / "Assets" / "Demo" / "x.cpp"
    assert precommit_cmd._check_value_reference(repo, [other]) == []
    ramps = repo / "Cluiche" / "Assets" / "Demo" / "y.ramps.json"
    assert precommit_cmd._check_value_reference(repo, [ramps]) != []
