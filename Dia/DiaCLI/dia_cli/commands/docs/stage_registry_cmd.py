"""dia docs stage-registry — auto-generate stage-registry.md from stage catalogue files."""
from __future__ import annotations

from pathlib import Path
from typing import Optional

import click

from dia_cli.utils.repo_root import find_repo_root
from dia_cli.utils.stage_catalogue import load, OK


def _escape_pipe(text: str) -> str:
    """Escape pipe characters in text for markdown tables."""
    return text.replace("|", "\\|")


def render_stage_registry(diagame_path: Path, game_name: str) -> str:
    """Render a single game's stage registry as a markdown table.

    Args:
        diagame_path: Path to the .diagame file
        game_name: Display name for the game

    Returns:
        Markdown text with a table for this game, or error note if load failed
    """
    result, catalogue = load(diagame_path)

    lines = []
    lines.append(f"## {game_name}")
    lines.append("")

    if result != OK:
        lines.append(f"> Catalogue load failed: {result}")
        lines.append("")
        return "\n".join(lines)

    if not catalogue or len(catalogue.entries) == 0:
        lines.append("> No stages in catalogue")
        lines.append("")
        return "\n".join(lines)

    # Build table
    lines.append("| Stage | Kinds | Tags | Description |")
    lines.append("|-------|-------|------|-------------|")

    for entry in catalogue.entries:
        kinds_str = ", ".join(entry.kinds) if entry.kinds else "-"
        tags_str = ", ".join(entry.tags) if entry.tags else "-"
        desc_str = _escape_pipe(entry.description)

        line = f"| {entry.name} | {kinds_str} | {tags_str} | {desc_str} |"
        lines.append(line)

    lines.append("")
    return "\n".join(lines)


def generate_stage_registry(repo_root: Path) -> str:
    """Generate the full stage registry document.

    Scans Cluiche/Assets/*/*.diagame files and produces markdown tables
    for each game with its stage catalogue.
    """
    output_lines = [
        "# Stage Registry",
        "",
        "> Auto-generated by `dia docs stage-registry`. Do not edit manually.",
        "",
        "---",
        "",
    ]

    # Find all .diagame files
    assets_dir = repo_root / "Cluiche" / "Assets"
    if not assets_dir.is_dir():
        output_lines.append("(No Cluiche/Assets directory found)")
        return "\n".join(output_lines) + "\n"

    diagame_files = sorted(assets_dir.rglob("*.diagame"))

    for diagame_path in diagame_files:
        # Extract game name from parent directory
        game_dir = diagame_path.parent.name
        game_name = game_dir

        table_text = render_stage_registry(diagame_path, game_name)
        output_lines.append(table_text)

    if not diagame_files:
        output_lines.append("(No .diagame files found)")

    return "\n".join(output_lines) + "\n"


@click.command("stage-registry")
@click.option("--dry-run", is_flag=True, default=False, help="Print to stdout instead of writing file.")
def stage_registry(dry_run: bool) -> None:
    """Regenerate docs/reference/registry/stage-registry.md from stage catalogue files.

    Scans all Cluiche/Assets/*/*.diagame files and produces a registry of stages
    for each game with their kinds, tags, and descriptions in Boot transition order.
    """
    repo_root = find_repo_root(__file__)
    content = generate_stage_registry(repo_root)

    if dry_run:
        click.echo(content)
        return

    out_path = repo_root / "docs" / "reference" / "registry" / "stage-registry.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    click.echo(f"[dia docs] Wrote {out_path.relative_to(repo_root)} ({content.count(chr(10))} lines)")
