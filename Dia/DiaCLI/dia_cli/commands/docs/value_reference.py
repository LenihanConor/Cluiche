"""dia docs value-reference: generate docs/reference/<app>/values.md from sidecars and the code-side export."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import click

from dia_cli.utils.repo_root import find_repo_root

HEADER_LINE = "Generated by `dia docs value-reference`, do not edit."
NO_EXPORT_LINE = ("Code-side tables (metrics, commands, component fields) are omitted because no export was found; "
                  "run `dia schema export`.")
UNDESCRIBED = "_undescribed_"


def _repo_root() -> Path:
    return find_repo_root(__file__)


# ---------------------------------------------------------------------------
# Cell formatting
# ---------------------------------------------------------------------------

def _cell(value: object) -> str:
    if value is None or value == "":
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float) and value == int(value) and abs(value) < 1e15:
        value = int(value)
    if isinstance(value, (list, dict)):
        value = json.dumps(value, sort_keys=True)
    text = str(value).replace("\r\n", "\n").replace("\r", "\n").strip()
    return text.replace("|", "\\|").replace("\n", "<br>")


def _code(value: object) -> str:
    text = _cell(value)
    return f"`{text}`" if text else ""


def _range(e: dict) -> str:
    lo, hi = e.get("min"), e.get("max")
    if lo is None and hi is None:
        return ""
    return f"{_cell(lo) or '...'} .. {_cell(hi) or '...'}"


def _list(values: object) -> str:
    return "<br>".join(f"`{_cell(v)}`" for v in values) if isinstance(values, list) else ""


def _table(headers: List[str], rows: List[List[str]]) -> List[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(" --- " for _ in headers) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def _desc(e: dict) -> str:
    d = _cell(e.get("description"))
    return d if d else UNDESCRIBED


# ---------------------------------------------------------------------------
# Inputs
# ---------------------------------------------------------------------------

def _resolve_app(target: str, repo_root: Path) -> str:
    from dia_cli.commands.validate import schema_discovery as sd
    name = sd._pipeline_app_name(target, repo_root) or target
    app_dir = next((d for d in sd._app_dirs(repo_root) if d.name.lower() == name.lower()), None)
    if app_dir is None:
        known = ", ".join(d.name for d in sd._app_dirs(repo_root)) or "none"
        raise click.UsageError(f"unknown --target '{target}' (no Cluiche/Assets/<App> directory; known apps: {known})")
    return app_dir.name


def page_path(app: str, repo_root: Path) -> Path:
    return repo_root / "docs" / "reference" / app.lower() / "values.md"


def _load_sidecars(target: str, repo_root: Path) -> List[dict]:
    from dia_cli.commands.validate import schema_discovery as sd
    docs: List[dict] = []
    for root in sd.target_roots(target, repo_root):
        for p in sd._walk(root, None):
            if not p.name.lower().endswith(".schema.json"):
                continue
            try:
                doc = json.loads(p.read_text(encoding="utf-8-sig"))
            except (OSError, ValueError, RecursionError):
                continue
            if isinstance(doc, dict) and isinstance(doc.get("for"), str) and isinstance(doc.get("entries"), list):
                docs.append(doc)
    return docs


def _load_export(target: str, repo_root: Path) -> Optional[dict]:
    from dia_cli.commands.validate import schema_codeside as cs
    path = cs.find_export(target, repo_root)
    if path is None:
        return None
    doc = cs.load_export(path)
    header = doc.get("header")
    if isinstance(header, dict) and header.get("code_side") is False:
        return None
    return doc


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------

def _format_sections(sidecars: List[dict]) -> List[str]:
    by_for: Dict[str, List[dict]] = {}
    for doc in sidecars:
        by_for.setdefault(doc["for"], []).extend(
            e for e in doc["entries"] if isinstance(e, dict) and isinstance(e.get("key"), str))
    lines = ["## Formats", ""]
    if not by_for:
        return lines + ["No `*.schema.json` sidecars found.", ""]
    for fmt in sorted(by_for):
        rows = []
        for e in sorted(by_for[fmt], key=lambda x: x["key"]):
            rows.append([_code(e["key"]), _cell(e.get("label")), _cell(e.get("type")), _cell(e.get("unit")),
                         _range(e), _cell(e.get("default")), _desc(e), _list(e.get("affects"))])
        lines += [f"### `{fmt}`", ""]
        lines += _table(["Key", "Label", "Type", "Unit", "Range", "Default", "Description", "Affects"], rows)
        lines.append("")
    return lines


def _arg_text(a: dict, cmd: str) -> str:
    name = a["key"][len(cmd) + 1:]
    meta = [_cell(a.get("type")), _range(a)]
    if a.get("default") is not None:
        meta.append(f"default {_cell(a.get('default'))}")
    meta = [m for m in meta if m]
    text = f"`{name}`" + (f" ({', '.join(meta)})" if meta else "")
    d = _cell(a.get("description"))
    return f"{text}: {d if d else UNDESCRIBED}"


def _code_side_sections(export: dict) -> List[str]:
    entries = [e for e in export.get("entries", []) if isinstance(e, dict) and isinstance(e.get("key"), str)
               and str(e.get("origin", "")).startswith("code:")]

    def of(kind: str) -> List[dict]:
        return sorted((e for e in entries if e.get("kind") == kind), key=lambda e: e["key"])

    lines = ["## Metrics", ""]
    lines += _table(["Metric", "Label", "Type", "Unit", "Range", "Description"],
                    [[_code(e["key"]), _cell(e.get("label")), _cell(e.get("type")), _cell(e.get("unit")),
                      _range(e), _desc(e)] for e in of("metric")])
    args = of("arg")
    rows = []
    for c in of("command"):
        ui = c.get("ui") if isinstance(c.get("ui"), dict) else {}
        mine = [a for a in args if a["key"].startswith(c["key"] + ".")]
        if mine:
            arg_cell = "<br>".join(_arg_text(a, c["key"]) for a in mine)
        else:
            arg_cell = "no arguments" if ui.get("no_args") is True else UNDESCRIBED
        rows.append([_code(c["key"]), _cell(ui.get("owner")), _cell(ui.get("category")), _desc(c), arg_cell,
                     _code(ui.get("example"))])
    lines += ["", "## Commands", ""]
    lines += _table(["Command", "Owner", "Category", "Description", "Arguments", "Example"], rows)
    lines += ["", "## Component fields", ""]
    lines += _table(["Field", "Type", "Unit", "Range", "Default", "Description"],
                    [[_code(e["key"]), _cell(e.get("type")), _cell(e.get("unit")), _range(e),
                      _cell(e.get("default")), _desc(e)] for e in of("component_field")])
    lines.append("")

    und = export.get("undescribed") if isinstance(export.get("undescribed"), dict) else {}

    def names(kind: str) -> List[str]:
        out = []
        items = und.get(kind)
        for it in items if isinstance(items, list) else []:
            n = it.get("name") if isinstance(it, dict) else it
            if isinstance(n, str):
                out.append(n)
        return sorted(set(out))

    lines += ["## Undescribed", ""]
    for label, kind in (("Metrics", "metrics"), ("Commands", "commands"), ("Component fields", "component_fields")):
        found = names(kind)
        suffix = " (" + ", ".join(f"`{_cell(n)}`" for n in found) + ")" if found else ""
        lines.append(f"- {label}: {len(found)}{suffix}")
    lines.append("")
    return lines


def render(app: str, sidecars: List[dict], export: Optional[dict]) -> str:
    lines = [f"# {app} value reference", "", f"> {HEADER_LINE}", ""]
    if export is not None:
        header = export.get("header") if isinstance(export.get("header"), dict) else {}
        lines += [f"Export commit: `{_cell(header.get('git_commit')) or 'unknown'}`", ""]
    lines += _format_sections(sidecars)
    lines += _code_side_sections(export) if export is not None else [NO_EXPORT_LINE, ""]
    return "\n".join(lines)


def generate(target: str, repo_root: Path) -> Tuple[Path, str]:
    app = _resolve_app(target, repo_root)
    text = render(app, _load_sidecars(target, repo_root), _load_export(target, repo_root))
    return page_path(app, repo_root), text


def is_current(path: Path, text: str) -> bool:
    if not path.is_file():
        return False
    return path.read_text(encoding="utf-8-sig").replace("\r\n", "\n") == text


def fix_command(target: str) -> str:
    return f"dia docs value-reference --target {target}"


# ---------------------------------------------------------------------------
# Precommit hook
# ---------------------------------------------------------------------------

def _trigger_apps(repo_root: Path, files: List[Path]) -> List[str]:
    assets = (repo_root / "Cluiche" / "Assets").resolve()
    ref = (repo_root / "docs" / "reference").resolve()
    apps: List[str] = []
    for f in files:
        rf = f.resolve()
        name = f.name.lower()
        app = None
        if (name.endswith(".schema.json") or name.endswith(".ramps.json")) and assets in rf.parents:
            app = rf.relative_to(assets).parts[0]
        elif name == "values.md" and rf.parent.parent == ref:
            app = rf.parent.name
        if app and app not in apps:
            apps.append(app)
    return apps


def precommit_warnings(repo_root: Path, files: List[Path]) -> List[str]:
    """WARN lines (never blocking) for apps whose reference page is out of date."""
    out: List[str] = []
    for app in _trigger_apps(repo_root, files):
        try:
            path, text = generate(app, repo_root)
        except (click.ClickException, OSError):
            continue
        if not is_current(path, text):
            out.append(f"reference out of date: {path.relative_to(repo_root).as_posix()} "
                       f"(run `{fix_command(app)}`)")
    return out


# ---------------------------------------------------------------------------
# Command
# ---------------------------------------------------------------------------

@click.command("value-reference")
@click.option("--target", required=True, help="Pipeline target or app name (e.g. cluichetest).")
@click.option("--check", is_flag=True, default=False, help="Exit 1 if the committed page differs; write nothing.")
def value_reference(target: str, check: bool) -> None:
    """Generate docs/reference/<app>/values.md from schema sidecars and the code-side export.

    Examples:
        dia docs value-reference --target cluichetest
        dia docs value-reference --target cluichetest --check
    """
    root = _repo_root()
    path, text = generate(target, root)
    rel = path.relative_to(root).as_posix()
    if check:
        if is_current(path, text):
            click.echo(f"[dia docs] {rel} is up to date.")
            return
        state = "is missing" if not path.is_file() else "is out of date"
        click.echo(f"[dia docs] {rel} {state}; run `{fix_command(target)}`.")
        raise SystemExit(1)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    click.echo(f"[dia docs] wrote {rel}")
